import argparse
import os
import sys
from dataclasses import dataclass

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import torch
import torch.nn as nn
import torch.optim as optim
from evaluation.classifier import MNISTClassifier
from torch.utils.data import DataLoader
from utils import get_device, get_logger, set_seed

from data import get_dataloader

# ============================== CONFIG ==============================
BATCH_SIZE = 128
N_EPOCHS = 10
LEARNING_RATE = 1.0e-3
SEED = 42
LOG_EVERY_N_BATCHES = 100
DATA_DIR = "./data"
CHECKPOINT_DIR = "./checkpoints"
RUN_NAME = "mnist_classifier"
# ======================================================================


@dataclass
class TrainConfig:
    batch_size: int = BATCH_SIZE
    n_epochs: int = N_EPOCHS
    lr: float = LEARNING_RATE
    seed: int = SEED
    log_every: int = LOG_EVERY_N_BATCHES
    data_dir: str = DATA_DIR
    checkpoint_dir: str = CHECKPOINT_DIR
    run_name: str = RUN_NAME

    @property
    def checkpoint_path(self) -> str:
        return os.path.join(self.checkpoint_dir, f"{self.run_name}.pth")


def parse_args() -> TrainConfig:
    """Parses CLI overrides for the CONFIG block above."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--epochs", type=int, default=N_EPOCHS)
    parser.add_argument("--lr", type=float, default=LEARNING_RATE)
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()
    return TrainConfig(
        batch_size=args.batch_size,
        n_epochs=args.epochs,
        lr=args.lr,
        seed=args.seed,
    )


def build_dataloaders(config: TrainConfig) -> tuple[DataLoader, DataLoader]:
    """Loads the MNIST train and test splits (unfiltered, all digits)."""
    train_loader = get_dataloader(
        batch_size=config.batch_size,
        train=True,
        data_dir=config.data_dir,
    )
    test_loader = get_dataloader(
        batch_size=config.batch_size,
        train=False,
        data_dir=config.data_dir,
    )
    return train_loader, test_loader


@torch.no_grad()
def evaluate(
    model: nn.Module, loader: DataLoader, device: torch.device
) -> tuple[float, float]:
    """Computes the mean loss and accuracy of `model` over `loader`.

    Runs without gradients (@torch.no_grad) and in eval mode. The loss
    is summed over every image and divided by the total count, so the
    mean stays exact even if the last batch is smaller.

    Args:
        model: Classifier returning logits of shape (B, 10).
        loader: DataLoader yielding (images, labels) batches.
        device: Device on which to run the evaluation.

    Returns:
        Tuple of (mean cross-entropy loss, accuracy in [0, 1]).
    """
    model.eval()
    loss_fn = nn.CrossEntropyLoss(reduction="sum")
    total_loss, correct, n = 0.0, 0, 0
    for x, y in loader:
        x, y = x.to(device), y.to(device)
        logits = model(x)
        total_loss += loss_fn(logits, y).item()
        correct += (logits.argmax(dim=1) == y).sum().item()
        n += y.size(0)
    return total_loss / n, correct / n


def train(config: TrainConfig) -> None:
    """Trains the classifier and saves it to `config.checkpoint_path`.

    Each epoch runs the standard supervised loop over the training set
    (zero_grad -> forward -> cross-entropy loss -> backward -> Adam
    step) and then logs the loss and accuracy on the test set, which is
    never used for training. The model saved is the one after the last
    epoch (the epoch count is fixed in advance, not chosen by looking
    at the test set).

    Args:
        config: Training configuration (see `TrainConfig`).
    """
    logger = get_logger(name=config.run_name)
    set_seed(config.seed)
    device = get_device()

    train_loader, test_loader = build_dataloaders(config)
    logger.info(
        "Training run '%s' | images=%d | device=%s",
        config.run_name,
        len(train_loader.dataset),
        device,
    )

    model = MNISTClassifier().to(device)
    optimizer = optim.Adam(model.parameters(), lr=config.lr)
    loss_fn = nn.CrossEntropyLoss()

    for epoch in range(config.n_epochs):
        model.train()
        running_loss = 0.0

        for i, (x, y) in enumerate(train_loader):
            x, y = x.to(device), y.to(device)

            optimizer.zero_grad()
            loss = loss_fn(model(x), y)
            loss.backward()
            optimizer.step()

            running_loss += loss.item()

            if i % config.log_every == 0:
                logger.info(
                    "[%d/%d] batch %d - loss: %.4f",
                    epoch + 1,
                    config.n_epochs,
                    i,
                    loss.item(),
                )

        test_loss, test_acc = evaluate(model, test_loader, device)
        logger.info(
            "Epoch %d - train loss: %.4f | test loss: %.4f | test acc: %.2f%%",
            epoch + 1,
            running_loss / len(train_loader),
            test_loss,
            100 * test_acc,
        )

    os.makedirs(config.checkpoint_dir, exist_ok=True)
    torch.save(model.state_dict(), config.checkpoint_path)
    logger.info(
        "Classifier saved to %s (final test acc: %.2f%%)",
        config.checkpoint_path,
        100 * test_acc,
    )


if __name__ == "__main__":
    train(parse_args())
