import torch
import torch.nn as nn


class MNISTClassifier(nn.Module):
    """Small CNN classifier over the 10 MNIST digit classes."""

    def __init__(self) -> None:
        """Initializes the MNISTClassifier.

        Builds two blocks:
            - `features`: two conv blocks (3x3 conv + ReLU + 2x2
              max-pool), each halving the spatial size (28 -> 14 -> 7).
              padding=1 keeps the size through the 3x3 convolutions,
              so only the pooling layers shrink it.
            - `head`: flatten, one hidden dense layer and one logit per
              digit. There is no softmax at the end: nn.CrossEntropyLoss
              applies it internally during training, and
              `evaluation/metrics.py` applies it explicitly.
        """
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(1, 32, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),
            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),
        )
        self.head = nn.Sequential(
            nn.Flatten(),
            nn.Linear(64 * 7 * 7, 128),
            nn.ReLU(),
            nn.Linear(128, 10),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Predicts class logits for a batch of MNIST-like images.

        Args:
            x: Input tensor of shape (B, 1, H, W), normalized to
                [-1, 1] as in `data/datasets.py`.

        Returns:
            Logits tensor of shape (B, 10).
        """
        return self.head(self.features(x))

    def embed(self, x: torch.Tensor) -> torch.Tensor:
        """Returns the 128-dimensional penultimate-layer features.

        Runs the network up to (and including) the ReLU after the
        hidden dense layer, i.e. everything except the final 10-logit
        layer. These features summarize what an image "looks like" to
        the classifier, and are what `evaluation/metrics.py::fd_mnist`
        compares between generated and real images (the same idea as
        FID, with this classifier in place of Inception).

        Args:
            x: Input tensor of shape (B, 1, H, W), normalized to
                [-1, 1] as in `data/datasets.py`.

        Returns:
            Feature tensor of shape (B, 128).
        """
        return self.head[:-1](self.features(x))
